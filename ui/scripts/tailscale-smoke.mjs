import assert from "node:assert/strict";
import { mkdir, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { createWorkbench } from "./workbench-fixture.mjs";
const engine = process.env.CAGE_TEST_BROWSER || "chromium";
const output = new URL(`../../docs/test-reports/2026-11-09-tailscale/${engine}/`, import.meta.url);
await mkdir(output, { recursive: true });
let copied = "", fail = false, delayed = false;
let tail = { installed: true, version: "1.104.5", enabled: false, backend: "Stopped", ips: [], peers: [], keys: [], user: "cage", ssh_port: 22 };
const { browser, page, state, errors } = await createWorkbench({ nativeRequest: body => { if (body.action === "clipboardWrite") { copied = body.text; return true; } } });
const checks = [];
const open = page.getByRole("button", { name: "打开 Tailscale", exact: true });
const panel = page.getByRole("dialog", { name: "Tailscale", exact: true });
try {
  await page.route("**/api/tailscale**", async route => {
    const request = route.request(), action = new URL(request.url()).pathname.split("/").at(-1), body = request.postDataJSON();
    if (fail) return route.fulfill({ status: 502, contentType: "text/plain", body: "Tailscale 暂未响应，请稍后重试" });
    if (["connect", "login"].includes(action)) tail = { ...tail, enabled: true, backend: "NeedsLogin", ...(delayed ? {} : { auth_url: "https://login.tailscale.com/a/fixture-login" }) };
    if (action === "disconnect") tail = { ...tail, enabled: false, backend: "Stopped" };
    if (action === "add-key") tail.keys.push(body.key);
    if (action === "remove-key") tail.keys = tail.keys.filter(key => key !== body.key);
    return route.fulfill({ json: tail });
  });
  state.status.ready = state.status.vm_running = true;
  await page.reload(); await open.waitFor();
  const position = await open.boundingBox(), browserPosition = await page.getByRole("button", { name: "打开浏览器", exact: true }).boundingBox();
  assert.ok(position.y > browserPosition.y && position.y < browserPosition.y + browserPosition.height * 2 + 8);
  await open.focus(); await page.keyboard.press("Enter"); await panel.getByText("已断开", { exact: true }).waitFor();
  await panel.getByRole("button", { name: "连接 Tailscale", exact: true }).click();
  await panel.waitFor({ state: "hidden" });
  assert.ok(state.requests.some(r => r.path === "/browser/new" && r.body.url === "https://login.tailscale.com/a/fixture-login" && r.body.incognito === false));
  checks.push("entry immediately follows Browser; keyboard opens panel; connect opens official auth URL in regular Cage browser");
  tail = { ...tail, enabled: true, backend: "Running", name: "cage-workbench.test.ts.net", auth_url: "", ips: ["100.88.2.3"], peers: [{ name: "my-computer.test.ts.net", ip: "100.88.2.4", online: true }] };
  await open.click(); await panel.getByText("已连接", { exact: true }).waitFor();
  await panel.getByRole("button", { name: "复制连接 Cage 命令" }).click(); assert.equal(copied, "ssh cage@100.88.2.3");
  await panel.getByLabel("本机 SSH 公钥", { exact: true }).fill("ssh-ed25519 AAAAFixture local");
  await panel.getByRole("button", { name: "添加公钥", exact: true }).click(); await panel.locator(".tailscale-key").waitFor();
  await page.screenshot({ path: fileURLToPath(new URL("connected.png", output)) });
  await panel.getByRole("button", { name: "移除 SSH 公钥" }).click(); await panel.locator(".tailscale-key").waitFor({ state: "hidden" });
  await panel.getByRole("button", { name: "复制命令", exact: true }).click(); assert.equal(copied, "ssh 本机用户名@100.88.2.4");
  checks.push("connected address, peer presence, inbound and outbound command copy, add and remove public key");
  await page.keyboard.press("Escape"); await panel.waitFor({ state: "hidden" });
  await open.click(); await panel.getByRole("button", { name: "断开连接", exact: true }).click();
  await page.getByRole("dialog", { name: "断开 Tailscale？", exact: true }).getByRole("button", { name: "取消", exact: true }).click();
  assert.equal(tail.enabled, true);
  await panel.getByRole("button", { name: "断开连接", exact: true }).click();
  await page.getByRole("dialog", { name: "断开 Tailscale？", exact: true }).getByRole("button", { name: "断开连接", exact: true }).click();
  await panel.getByText("已断开", { exact: true }).waitFor();
  checks.push("closing and reopening retains status; cancel preserves active connection; explicit disconnect closes connection");
  delayed = true; delete tail.auth_url;
  await panel.getByRole("button", { name: "连接 Tailscale", exact: true }).click();
  await panel.getByText("等待登录", { exact: true }).waitFor();
  tail.auth_url = "https://login.tailscale.com/a/delayed-login";
  await panel.waitFor({ state: "hidden" });
  assert.ok(state.requests.some(r => r.path === "/browser/new" && r.body.url === tail.auth_url));
  checks.push("asynchronously generated auth URL opens without a second login click");
  fail = true; await open.click(); await panel.getByRole("alert").waitFor(); assert.ok(await panel.getByRole("alert").textContent());
  fail = false; await panel.getByRole("button", { name: "刷新 Tailscale 状态" }).click(); await panel.getByRole("alert").waitFor({ state: "hidden" });
  await page.setViewportSize({ width: 820, height: 600 });
  await page.screenshot({ path: fileURLToPath(new URL("compact.png", output)) });
  assert.ok(await panel.evaluate(node => node.scrollWidth <= node.clientWidth + 1));
  assert.deepEqual(errors, []);
  checks.push("service failure is actionable, refresh recovers, compact panel has no horizontal overflow, no browser exceptions");
  await writeFile(new URL("result.json", output), JSON.stringify({ engine, checks, errors }, null, 2));
  console.log(JSON.stringify({ engine, checks, errors }, null, 2));
} finally { await browser.close(); }
